// ن۴۹: نگاشت نویسه‌های بی‌گلیف به نزدیک‌ترین گلیف (قبلاً «؟» می‌شدند) — حروف کوچک لاتین → بزرگ، عربی → فارسی، نمادها
const ALIAS = { '\u0622': '\u0627', '\u0623': '\u0627', '\u0625': '\u0627', '\u0671': '\u0627', '\u064a': '\u06cc', '\u0649': '\u06cc', '\u0626': '\u06cc', '\u0643': '\u06a9', '\u0629': '\u0647', '\u0624': '\u0648', '\u066a': '%', '\u2014': '-', '\u2013': '-', '\u2192': '-', '\\': '/', '&': '+', '\u066b': '.', '\u00d7': '\u00d7' };
const SKIP = /[\u200c\u200d\u200e\u200f\u0640\u064b-\u065f]/g; // نیم‌فاصله/کشیده/اعراب: عرض صفر
const LTR_RUN = /[A-Za-z0-9\u06f0-\u06f9\u0660-\u0669]+(?:[.,:\/%\u00d7x-][A-Za-z0-9\u06f0-\u06f9\u0660-\u0669]+)*/g;
const resolve = (ch) => {
  if (GLYPHS[ch]) return ch;
  if (ALIAS[ch]) return ALIAS[ch];
  const c = ch.charCodeAt(0);
  if (c >= 0x660 && c <= 0x669) return String.fromCharCode(0x6f0 + c - 0x660); // ارقام عربی-هندی → فارسی
  const u = ch.toUpperCase();
  return GLYPHS[u] ? u : ch;
};
// ترتیب نمایش: رشته‌ی فارسی کامل برعکس می‌شود، سپس ردیف‌های ارقام/لاتین دوباره راست‌به‌چپِ-معکوس → خوانا (قبلاً «۱۲۳» → «۳۲۱»)
const prep = (s) => {
  s = String(s).replace(SKIP, '');
  if (!FA.test(s)) return s;
  return [...s].reverse().join('').replace(LTR_RUN, (m) => [...m].reverse().join(''));
};
const H = 9;
const _adv = new Map();
const _mask = new Map();
const _outl = new Map();
const FA = /[؀-ۿ]/;

function glyph(ch) {
  let m = _mask.get(ch);
  if (m === undefined) {
    const rows = (GLYPHS[resolve(ch)] || GLYPHS['?'] || '').split('/');
    const w = rows[0].length || 3;
    m = { w, a: new Uint8Array(w * H) };
    for (let y = 0; y < H; y++) for (let x = 0; x < w; x++) if (rows[y] && rows[y][x] === '#') m.a[y * w + x] = 1;
    _mask.set(ch, m);
    _adv.set(ch, w + 1);
  }
  return m;
}
function outlineMask(ch) {
  let o = _outl.get(ch);
  if (o === undefined) {
    const g = glyph(ch), w = g.w, a = new Uint8Array((w + 2) * (H + 2));
    for (let y = 0; y < H; y++) for (let x = 0; x < w; x++) if (g.a[y * w + x]) {
      a[(y + 1) * (w + 2) + x + 1] = 2;
      a[y * (w + 2) + x + 1] = Math.max(a[y * (w + 2) + x + 1], 1);
      a[(y + 2) * (w + 2) + x + 1] = Math.max(a[(y + 2) * (w + 2) + x + 1], 1);
      a[(y + 1) * (w + 2) + x] = Math.max(a[(y + 1) * (w + 2) + x], 1);
      a[(y + 1) * (w + 2) + x + 2] = Math.max(a[(y + 1) * (w + 2) + x + 2], 1);
    }
    o = { w: w + 2, a };
    _outl.set(ch, o);
  }
  return o;
}

export function textW(s, sc = 1) {
  s = String(s).replace(SKIP, '');
  let w = 0;
  for (const ch of s) w += (_adv.get(ch) ?? glyph(ch).w + 1);
  return (w - 1) * sc;
}

const _oc = [20, 16, 33, 255];
export function drawText(r, s, x, y, col, sc = 1, o = null) {
  x = Math.round(x); y = Math.round(y);
  s = prep(s);
  const outline = !!(o && o.outline);
  const sh = !!(o && o.shadow);
  const oc = _oc;
  if (outline) oc[3] = col[3] ?? 255;
  let cx = x;
  for (const ch of s) {
    if (outline) {
      const m = outlineMask(ch), w2 = m.w;
      for (let yy = 0; yy < H + 2; yy++) for (let xx = 0; xx < w2; xx++) {
        if (m.a[yy * w2 + xx] === 1) {
          const px = cx - sc + xx * sc, py = y - sc + yy * sc;
          if (sc === 1) r.px(px, py, oc); else r.rect(px, py, sc, sc, oc);
        }
      }
    }
    const g = glyph(ch), w = g.w;
    for (let yy = 0; yy < H; yy++) for (let xx = 0; xx < w; xx++) if (g.a[yy * w + xx]) {
      const px = cx + xx * sc, py = y + yy * sc;
      if (sc === 1) r.px(px, py, col); else r.rect(px, py, sc, sc, col);
    }
    if (sh) for (let xx = 0; xx < w; xx++) {
      let yy = H - 1; while (yy >= 0 && !g.a[yy * w + xx]) yy--;
      if (yy >= 0) { const px = cx + xx * sc, py = y + (yy + 1) * sc; if (sc === 1) r.px(px, py, col); else r.rect(px, py, sc, sc, col); }
    }
    cx += (w + 1) * sc;
  }
}
export function drawTextC(r, s, cx, y, col, sc = 1, o = null) { drawText(r, s, Math.round(cx - textW(s, sc) / 2), y, col, sc, o); }
