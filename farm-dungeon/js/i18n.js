let lang = 'fa';
const listeners = new Set();
export const t = (k) => (STR[k] ? STR[k][lang] : k);
export const getLang = () => lang;
export const faNum = (n) => (lang === 'fa' ? String(n).replace(/\d/g, (d) => '۰۱۲۳۴۵۶۷۸۹'[d]) : String(n));
export function setLang(l) {
  lang = l;
  document.documentElement.lang = l;
  document.documentElement.dir = l === 'fa' ? 'rtl' : 'ltr';
  listeners.forEach((f) => f());
}
export function toggleLang() { setLang(lang === 'fa' ? 'en' : 'fa'); }
export function onLangChange(f) { listeners.add(f); }
export function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
}
