def row(*segs):
    s = ''
    for seg in segs:
        if isinstance(seg, str):
            s += seg
        else:
            ch, n = seg
            s += ch * n
    assert len(s) == 30, f'طول {len(s)} (باید ۳۰): {s!r}'
    return s

def g(name, rows):
    assert len(rows) == 20, name
    for r in rows:
        assert len(r) == 30, (name, r)
        assert set(r) <= set('#.S>CHTPWDREB'), (name, r)
    j = ''.join(rows)
    assert j.count('S') == 1, (name, 'S')
    assert j.count('>') == 1, (name, '>')
    # اتصال S→>
    grid = [list(r) for r in rows]
    start = end = None
    for y in range(20):
        for x in range(30):
            if rows[y][x] == 'S': start = (x, y)
            if rows[y][x] == '>': end = (x, y)
    st = [start]; seen = {start}
    while st:
        x, y = st.pop()
        for dx, dy in ((1,0),(-1,0),(0,1),(0,-1)):
            nx, ny = x+dx, y+dy
            if 0 <= nx < 30 and 0 <= ny < 20 and (nx, ny) not in seen and rows[ny][nx] not in BLOCK:
                seen.add((nx, ny)); st.append((nx, ny))
    assert end in seen, f'{name}: پله از اسپاون قابل‌دسترس نیست!'
    st_ = lambda ch: j.count(ch)
    stats = {ch: st_(ch) for ch in 'PCDEHT'}
    assert stats['P'] >= 3 and stats['C'] >= 2 and stats['D'] >= 2 and stats['E'] >= 3 and stats['H'] >= 1, (name, stats)
    return {'name': name, 'rows': rows, 'stats': stats}

