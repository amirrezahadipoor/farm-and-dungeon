G = {}

def g(name, rows, w=None):
    assert len(rows) == 9, (name, len(rows))
    w = w or max(len(r) for r in rows)
    for r in rows:
        assert len(r) == w, (name, r)
        assert set(r) <= set('.#'), (name, r)
    G[name] = rows

